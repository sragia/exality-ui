"""Generates flight timer seed data (hop distances) from wago.tools DB2 exports.

Usage: python tools/generate-flight-data.py
Writes ExalityUI/Modules/FlightTimer/Data/Retail.lua and Forever.lua.
"""
import csv
import io
import math
import os
import urllib.request
from collections import defaultdict

PRODUCTS = {
    'Retail': ('wow', 'IsRetail'),
    'Forever': ('wowf', 'IsForever'),
}
FLAG_TELEPORT = 0x1
FLAG_STOP = 0x2
OUT_DIR = os.path.join(os.path.dirname(__file__), '..', 'ExalityUI', 'Modules', 'FlightTimer', 'Data')


def fetch(table, product):
    url = f'https://wago.tools/db2/{table}/csv?product={product}'
    req = urllib.request.Request(url, headers={'User-Agent': 'flight-data-generator'})
    with urllib.request.urlopen(req, timeout=120) as res:
        return list(csv.DictReader(io.StringIO(res.read().decode('utf-8'))))


def build(product):
    paths = fetch('TaxiPath', product)
    points = defaultdict(list)
    for row in fetch('TaxiPathNode', product):
        points[int(row['PathID'])].append(row)

    seed = {}
    for path in paths:
        from_node, to_node = int(path['FromTaxiNode']), int(path['ToTaxiNode'])
        nodes = sorted(points.get(int(path['ID']), []), key=lambda r: int(r['NodeIndex']))
        if from_node == 0 or to_node == 0 or len(nodes) < 2:
            continue

        distance = 0.0
        delay = 0
        for prev, cur in zip(nodes, nodes[1:]):
            if int(cur['Flags']) & FLAG_TELEPORT or prev['ContinentID'] != cur['ContinentID']:
                continue
            distance += math.dist(
                (float(prev['Loc_0']), float(prev['Loc_1']), float(prev['Loc_2'])),
                (float(cur['Loc_0']), float(cur['Loc_1']), float(cur['Loc_2'])),
            )
        for node in nodes:
            if int(node['Flags']) & FLAG_STOP:
                delay += int(node['Delay'])

        if distance > 0:
            seed[from_node * 10000 + to_node] = (round(distance), delay)
    return seed


def write(name, check, seed):
    lines = [
        '---@class ExalityUI',
        'local EXUI = select(2, ...)',
        '',
        f'if not EXUI.{check}() then return end',
        '',
        '-- Generated by tools/generate-flight-data.py. [from * 10000 + to] = { distanceYards, delaySeconds }',
        'EXUI.flightTimerSeed = {',
    ]
    for key in sorted(seed):
        distance, delay = seed[key]
        lines.append(f'    [{key}] = {{ {distance}, {delay} }},')
    lines.append('}')
    lines.append('')

    os.makedirs(OUT_DIR, exist_ok=True)
    with open(os.path.join(OUT_DIR, f'{name}.lua'), 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines))
    print(f'{name}: {len(seed)} hops')


if __name__ == '__main__':
    for name, (product, check) in PRODUCTS.items():
        write(name, check, build(product))
